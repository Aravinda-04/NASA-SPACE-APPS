import { writeFile } from 'node:fs/promises';

// One request at a time, as required by the JPL SSD API fair-use policy.
// Positions are reconstructed from each body's true anomaly and osculating
// elements at exactly the same epoch; no runtime request or clock is involved.
const definitions = [
  ['mercury', 'Mercury', '199', '#aaa59d', 3],
  ['venus', 'Venus', '299', '#dac58e', 5],
  ['earth', 'Earth', '399', '#78b3c0', 5],
  ['mars', 'Mars', '499', '#c77a52', 4],
  ['jupiter', 'Jupiter', '599', '#ccaa86', 9],
  ['saturn', 'Saturn', '699', '#d8c794', 8],
  ['uranus', 'Uranus', '799', '#9bcdd0', 6],
  ['neptune', 'Neptune', '899', '#739ad5', 6],
  ['eros', 'Eros', '433;', '#c6b8a3', 2.5],
  ['vesta', 'Vesta', '4;', '#a7a79b', 3],
  ['ceres', 'Ceres', '1;', '#a2a79d', 3.5],
  ['heliocentric', 'Kepler', '-227', '#e6ca7a', 3],
];
const bodies = [];
for (const [id, name, command, color, markerPixels] of definitions) {
  const parameters = new URLSearchParams({
    format: 'json', COMMAND: command, EPHEM_TYPE: 'ELEMENTS', CENTER: '500@10',
    TLIST: '2458421.5', OUT_UNITS: 'AU-D', REF_PLANE: 'ECLIPTIC',
    REF_SYSTEM: 'J2000', CSV_FORMAT: 'YES',
  });
  const source = `https://ssd.jpl.nasa.gov/api/horizons.api?${parameters}`;
  const response = await fetch(source, { signal: AbortSignal.timeout(60000) });
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
  const payload = await response.json();
  const result = payload.result ?? '';
  const row = result.split('$$SOE')[1]?.split('$$EOE')[0]?.trim().split(',').map(value => value.trim());
  if (payload.error || !row || Number(row[0]) !== 2458421.5) throw new Error(`${name}: ${payload.error ?? result}`);
  const elements = {
    eccentricity: Number(row[2]), inclination: Number(row[4]), ascendingNode: Number(row[5]),
    argumentOfPeriapsis: Number(row[6]), trueAnomaly: Number(row[10]), semiMajorAxis: Number(row[11]),
  };
  if (!Object.values(elements).every(Number.isFinite) || elements.eccentricity >= 1 || elements.eccentricity < 0 || elements.semiMajorAxis <= 0)
    throw new Error(`${name}: invalid elliptic elements`);
  const target = result.match(/Target body name: (.+)/)?.[1]?.trim();
  bodies.push({ id, name, kind: bodies.length < 8 ? 'planet' : id === 'heliocentric' ? 'spacecraft' : 'minor-body', color, markerPixels, elements, target, source });
  console.log(`${name}: a=${elements.semiMajorAxis.toFixed(5)} AU, e=${elements.eccentricity.toFixed(5)}`);
}
const header = '// Generated by scripts/update-solar-ephemeris.mjs from NASA/JPL Horizons.\n// Heliocentric geometric elements, J2000 ecliptic, 2018-10-30 00:00 TDB (JD 2458421.5).\n';
await writeFile(new URL('../src/data/solarEphemeris.ts', import.meta.url), `${header}export const SOLAR_EPHEMERIS = ${JSON.stringify(bodies, null, 2)} as const;\n`);
